import { mkdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { canonicalRoutes } from "../src/seo/routes";
import { absoluteUrl, site, titleWithSuffix } from "../src/seo/site";
import { tools } from "../src/tools/registry";
import {
  checkHtml,
  checkLinks,
  chunkSizes,
  initialGzip,
  type Issue,
} from "./lib/checks";
import { inspectHtml, routeFile } from "./lib/html";

const ROOT = process.cwd();
const CLIENT = join(ROOT, "dist", "client");
const INITIAL_JS_BUDGET = 75 * 1024;

type Handler = (request: Request) => Promise<Response>;

async function loadHandler(): Promise<Handler> {
  const server = (await import("../dist/server/server.js")) as { handleRequest: Handler };
  if (typeof server.handleRequest !== "function") {
    throw new Error("dist/server/server.js does not export handleRequest.");
  }
  return server.handleRequest;
}

async function render(handleRequest: Handler, path: string): Promise<Response> {
  return handleRequest(new Request(absoluteUrl(path)));
}

function xmlEscape(value: string): string {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function sitemap(): string {
  const urls = canonicalRoutes
    .map((route) => {
      const lastmod = route.updated ? `<lastmod>${route.updated}</lastmod>` : "";
      return `  <url><loc>${xmlEscape(absoluteUrl(route.path))}</loc>${lastmod}</url>`;
    })
    .join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`;
}

function headersFile(): string {
  const plausible = process.env.VITE_PLAUSIBLE_DOMAIN ? " https://plausible.io" : "";
  return `# Generated by scripts/prerender.ts
/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: DENY
  Permissions-Policy: camera=(), microphone=(), geolocation=(), interest-cohort=()
  Cross-Origin-Opener-Policy: same-origin
  Content-Security-Policy: default-src 'self'; script-src 'self' 'unsafe-inline'${plausible}; style-src 'self' 'unsafe-inline'; img-src 'self' data:; font-src 'self'; connect-src 'self'${plausible}; frame-ancestors 'none'; base-uri 'self'; form-action 'self'

/assets/*
  Cache-Control: public, max-age=31536000, immutable

/fonts/*
  Cache-Control: public, max-age=31536000, immutable
`;
}

function redirectsFile(): string {
  const lines = canonicalRoutes
    .filter((route) => route.path !== "/")
    .map((route) => `${route.path}/ ${route.path} 301`);
  return `${lines.join("\n")}\n`;
}

function adsTxt(): string | null {
  const client = process.env.VITE_ADSENSE_CLIENT ?? "";
  return client.length > 0 ? `google.com, ${client}, DIRECT, f08c47fec0942fa0\n` : null;
}

async function main(): Promise<void> {
  const handleRequest = await loadHandler();
  const failures: Issue[] = [];

  await rm(join(CLIENT, "404.html"), { force: true });
  await mkdir(CLIENT, { recursive: true });

  for (const route of canonicalRoutes) {
    const response = await render(handleRequest, route.path);
    const html = await response.text();
    const file = routeFile(route.path);

    if (response.status !== 200) {
      failures.push({ path: route.path, message: `Expected 200, got ${response.status}.` });
      continue;
    }

    failures.push(
      ...checkHtml(route.path, html, {
        path: route.path,
        title: titleWithSuffix(route.title),
        description: route.description,
        canonical: absoluteUrl(route.path),
      }),
    );

    const facts = inspectHtml(html);
    if (facts.links.length === 0) {
      failures.push({ path: route.path, message: "No internal links found." });
    }

    await writeFile(join(CLIENT, file), html, "utf8");
  }

  const missing = await render(handleRequest, "/__not-found__");
  const missingHtml = await missing.text();
  if (missing.status !== 404) {
    failures.push({ path: "/404", message: `Expected 404, got ${missing.status}.` });
  }
  if (!missingHtml.includes('name="robots"') || !missingHtml.includes("noindex")) {
    failures.push({ path: "/404", message: "404 page is not marked noindex." });
  }
  await writeFile(join(CLIENT, "404.html"), missingHtml, "utf8");

  const htmlFiles = [...canonicalRoutes.map((route) => routeFile(route.path)), "404.html"];
  failures.push(...(await checkLinks(htmlFiles, CLIENT)));

  const initial = await initialGzip(CLIENT);
  if (initial > INITIAL_JS_BUDGET) {
    failures.push({
      path: "/",
      message: `Initial JS is ${(initial / 1024).toFixed(1)} KB gzip, over the ${INITIAL_JS_BUDGET / 1024} KB budget.`,
    });
  }

  const chunks = await chunkSizes(CLIENT);
  await writeFile(join(CLIENT, "sitemap.xml"), sitemap(), "utf8");
  await writeFile(
    join(CLIENT, "robots.txt"),
    `User-agent: *\nAllow: /\n\nSitemap: ${absoluteUrl("/sitemap.xml")}\n`,
    "utf8",
  );
  await writeFile(join(CLIENT, "_headers"), headersFile(), "utf8");
  await writeFile(join(CLIENT, "_redirects"), redirectsFile(), "utf8");
  const ads = adsTxt();
  if (ads) await writeFile(join(CLIENT, "ads.txt"), ads, "utf8");

  const report = {
    generatedAt: new Date().toISOString(),
    site: site.url,
    routes: canonicalRoutes.length,
    tools: tools.length,
    initialJsGzipBytes: initial,
    chunks,
    failures,
  };
  await writeFile(join(ROOT, "dist", "build-report.json"), `${JSON.stringify(report, null, 2)}\n`);

  if (failures.length > 0) {
    console.error("Prerender checks failed:");
    for (const issue of failures) console.error(`  ${issue.path}: ${issue.message}`);
    process.exitCode = 1;
    return;
  }

  console.log(
    `Prerendered ${canonicalRoutes.length} routes, ${tools.length} tools, ${(initial / 1024).toFixed(1)} KB initial JS gzip.`,
  );
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.stack ?? error.message : error);
  process.exitCode = 1;
});
